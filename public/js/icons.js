export function icon(name, size = 15, extraClass = '') {
  const path = SVG_PATHS[name] || '';
  return `<svg class="svg-icon ${extraClass}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

export function hydrateSvgIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    const name = el.getAttribute('data-icon');
    const size = parseInt(el.getAttribute('data-size') || '15', 10);
    el.innerHTML = icon(name, size);
  });
}

export function escapeHtml(str = '') {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Formatea Markdown básico con protección de HTML (anti-XSS) y preservación de bloques LaTeX.
 */
export function formatMarkdownSafe(text = '') {
  if (!text) return '';

  const mathTokens = [];
  let tokenized = String(text).replace(/\$\$[\s\S]*?\$\$|\\\[[\s\S]*?\\\]|\\\([^\n]+?\\\)|\$[^\n$]+\$/g, (m) => {
    const idx = mathTokens.length;
    mathTokens.push(m);
    return `@@MATH_${idx}@@`;
  });

  let safe = escapeHtml(tokenized)
    .replace(/^---+\s*$/gm, '<hr class="md-divider">')
    .replace(/^###\s+(.*)$/gm, '<div class="md-h3">$1</div>')
    .replace(/^##\s+(.*)$/gm, '<div class="md-h2">$1</div>')
    .replace(/^\s*[\*\-]\s+(.*)$/gm, '<div class="md-li">• $1</div>')
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^\*])\*([^\n\*]+?)\*/g, '$1<em>$2</em>')
    .replace(/\n\n+/g, '<br><br>')
    .replace(/\n/g, '<br>');

  mathTokens.forEach((orig, idx) => {
    const safeMath = escapeHtml(orig);
    safe = safe.replace(`@@MATH_${idx}@@`, safeMath);
  });

  return safe;
}

let toastStackEl = null;

export function showToast(message, tone = 'info', durationMs = 2800) {
  if (!toastStackEl) {
    toastStackEl = document.createElement('div');
    toastStackEl.className = 'toast-stack';
    document.body.appendChild(toastStackEl);
  }
  const item = document.createElement('div');
  item.className = `toast-item toast-${tone}`;
  item.innerHTML = `${icon(tone === 'success' ? 'check' : tone === 'warn' ? 'alert' : 'sparkles', 14)}<span>${escapeHtml(message)}</span>`;
  toastStackEl.appendChild(item);

  setTimeout(() => {
    item.classList.add('is-leaving');
    setTimeout(() => item.remove(), 180);
  }, durationMs);
}

/**
 * Conecta SSE /api/live/stream con fallback automático de polling lento si falla la conexión.
 */
export function connectLiveStateSync(onVersionChange) {
  let lastVersion = -1;
  let fallbackTimer = null;
  let es = null;

  const triggerSync = (versionHint = null) => {
    if (versionHint !== null && versionHint === lastVersion) return;
    if (versionHint !== null) lastVersion = versionHint;
    onVersionChange();
  };

  try {
    es = new EventSource('/api/live/stream');
    es.addEventListener('state', (ev) => {
      try {
        const parsed = JSON.parse(ev.data);
        triggerSync(parsed.stateVersion ?? null);
      } catch (_) {
        triggerSync(null);
      }
    });
    es.onerror = () => {
      if (!fallbackTimer) {
        fallbackTimer = setInterval(() => onVersionChange(), 8000);
      }
    };
  } catch (_) {
    fallbackTimer = setInterval(() => onVersionChange(), 6000);
  }

  return () => {
    if (es) es.close();
    if (fallbackTimer) clearInterval(fallbackTimer);
  };
}
